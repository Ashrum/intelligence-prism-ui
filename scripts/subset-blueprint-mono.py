"""Rebuild the Blueprint-only Latin subsets from pinned official Geist sources.

Requires Python 3.12, fonttools==4.60.1 and brotli==1.1.0; no npm dependency.
Run from any directory: python scripts/subset-blueprint-mono.py [--check]
The upstream cache lives in ignored .sites-runtime; outputs retain the upstream OFL.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path
from urllib.request import urlopen

import brotli
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public/fonts/blueprint"
CACHE = ROOT / ".sites-runtime/editorial-20261016/upstream"
COMMIT = "4d655731f83507f0258ce5541c297b6553d5d081"
BASE = f"https://raw.githubusercontent.com/vercel/geist-font/{COMMIT}/"
SOURCE_DIR = "packages/next/dist/fonts/geist-mono/"
SOURCES = {
    400: ("GeistMono-Regular.ttf", "dee3e2532c8db2b36dced0b9ddf9834e4b5a83ba8afecd01be0a97d4b0c13d7f"),
    500: ("GeistMono-Medium.ttf", "0b3a59c0273781c4d2b3713cf5f8cffebb25a060ebfde415c74ec61465657fcc"),
}
LICENSE_SHA = "1781d2806a07d91c4edf4740b88449fab7d0eadad53f7c351b94cd4d4eb8c00f"
REQUESTED = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(range(0x2010, 0x2016)) | set(range(0x2018, 0x2020)) | {0x2022, 0x2026, 0x2030, 0x2032, 0x2033, 0x20AC}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def source(path, expected):
    local = CACHE / Path(path).name
    if not local.exists():
        local.parent.mkdir(parents=True, exist_ok=True)
        with urlopen(BASE + path, timeout=60) as response:
            local.write_bytes(response.read())
    data = local.read_bytes()
    if sha(data) != expected:
        raise ValueError(f"Source hash mismatch: {path}")
    return data


def unicode_range(points):
    runs = []
    start = end = None
    for point in sorted(points):
        if end is not None and point == end + 1:
            end = point
        else:
            if start is not None:
                runs.append((start, end))
            start = end = point
    if start is not None:
        runs.append((start, end))
    return ", ".join(f"U+{start:04X}" + (f"-{end:04X}" if end != start else "") for start, end in runs)


def main():
    args = argparse.ArgumentParser()
    args.add_argument("--check", action="store_true", help="Rebuild in memory and compare exact delivered bytes")
    check = args.parse_args().check
    if fontTools.__version__ != "4.60.1" or brotli.__version__ != "1.1.0":
        raise RuntimeError("Use fonttools==4.60.1 and brotli==1.1.0 for reproducible output")
    manifest = {"family": "Geist Mono Blueprint", "sourceRepository": "https://github.com/vercel/geist-font", "sourceTag": "1.4.2", "sourceCommit": COMMIT, "license": "OFL-1.1", "licenseUrl": BASE + "OFL.txt", "licenseSha256": LICENSE_SHA, "toolchain": {"fontTools": fontTools.__version__, "brotli": brotli.__version__}, "fontDisplay": "swap", "fonts": []}
    outputs = {OUT / "OFL.txt": source("OFL.txt", LICENSE_SHA)}
    css = ["/* Generated by scripts/subset-blueprint-mono.py; pinned sources and hashes are in public/fonts/blueprint/manifest.json. */"]
    for weight, (filename, expected) in SOURCES.items():
        original = source(SOURCE_DIR + filename, expected)
        font = TTFont(io.BytesIO(original), recalcTimestamp=False)
        assert "fvar" not in font and font["OS/2"].usWeightClass == weight
        original_glyphs = len(font.getGlyphOrder())
        options = subset.Options()
        options.recalc_timestamp = False
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
        options.name_legacy = True
        options.name_languages = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=REQUESTED)
        subsetter.subset(font)
        font.flavor = "woff2"
        buffer = io.BytesIO()
        font.save(buffer)
        result = buffer.getvalue()
        actual = set(font.getBestCmap())
        assert actual <= REQUESTED and set(range(0x20, 0x7F)) <= actual
        assert len(font.getGlyphOrder()) < original_glyphs and len(result) < len(original)
        ranges = unicode_range(actual)
        target = f"geist-mono-latin-{weight}.woff2"
        outputs[OUT / target] = result
        manifest["fonts"].append({"weight": weight, "file": target, "sourceUrl": BASE + SOURCE_DIR + filename, "sourceBytes": len(original), "sourceSha256": expected, "bytes": len(result), "sha256": sha(result), "glyphCount": len(font.getGlyphOrder()), "codepointCount": len(actual), "unicodeRange": ranges})
        css.append(f'@font-face {{ font-family:"Geist Mono Blueprint"; src:url("/fonts/blueprint/{target}") format("woff2"); font-style:normal; font-weight:{weight}; font-display:swap; unicode-range:{ranges}; }}')
    outputs[OUT / "manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode()
    outputs[ROOT / "app/(next)/next/blueprint-fonts.css"] = ("\n".join(css) + "\n").encode()
    for path, data in outputs.items():
        if check:
            assert path.read_bytes() == data, f"Generated file differs: {path.relative_to(ROOT)}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(json.dumps({"mode": "check" if check else "write", "fonts": manifest["fonts"]}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
